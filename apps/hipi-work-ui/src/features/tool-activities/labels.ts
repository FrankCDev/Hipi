export function activityLabels(locale: string) {
	return locale === "en" ? en : zh;
}
export function toolLabel(name: string, locale: string) {
	const labels = activityLabels(locale);
	switch (name) {
		case "hipi_files_read":
			return labels["activity.tool.read_file"];
		case "hipi_files_save":
			return labels["activity.tool.write_file"];
		case "hipi_files_list":
			return labels["activity.tool.list_files"];
		default:
			return name;
	}
}
