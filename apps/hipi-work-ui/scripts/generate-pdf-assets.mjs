// Regenerate reviewed static imports and notices after an explicitly reviewed PDF.js upgrade.
import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = dirname(require.resolve("pdfjs-dist/package.json"));
const app = fileURLToPath(new URL("../", import.meta.url));
const metadata = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
if (metadata.version !== "6.4.299") throw new Error("Review the PDF.js asset manifest before upgrading");
const groups = { cMapUrl: "cmaps", standardFontDataUrl: "standard_fonts" };
const imports = [], maps = [], inventory = [];
let index = 0;
for (const [kind, folder] of Object.entries(groups)) {
	const files = (await readdir(join(root, folder))).filter(name => /\.(bcmap|pfb|ttf)$/.test(name)).sort();
	const entries = [];
	for (const name of files) {
		const symbol = `asset${index++}`;
		imports.push(`import ${symbol} from ${JSON.stringify(`pdfjs-dist/${folder}/${name}?url&inline`)};`);
		entries.push(`\t\t${JSON.stringify(name)}: ${symbol},`);
		const data = await readFile(join(root, folder, name));
		inventory.push({ file: `${folder}/${name}`, bytes: data.length, sha256: createHash("sha256").update(data).digest("hex") });
	}
	maps.push(`\t${kind}: Object.freeze({\n${entries.join("\n")}\n\t}),`);
}
await writeFile(join(app, "src/features/files/pdf-assets.generated.ts"),
	`// Generated by scripts/generate-pdf-assets.mjs from pdfjs-dist ${metadata.version}.\n// Explicit inline assets keep connect-src 'none': no URL is fetched or derived from a document.\n// Distribution notices and hashes: vendor/pdfjs/asset-inventory.json.\n${imports.join("\n")}\n\nexport const PDF_LOCAL_ASSETS = Object.freeze({\n${maps.join("\n")}\n});\n`);
const vendor = join(app, "vendor/pdfjs");
await mkdir(vendor, { recursive: true });
const licenses = { "LICENSE": "LICENSE_PDFJS", "cmaps/LICENSE": "LICENSE_CMAPS", "standard_fonts/LICENSE_FOXIT": "LICENSE_FOXIT", "standard_fonts/LICENSE_LIBERATION": "LICENSE_LIBERATION" };
for (const [source, destination] of Object.entries(licenses)) await copyFile(join(root, source), join(vendor, destination));
await writeFile(join(vendor, "asset-inventory.json"), JSON.stringify({ package: "pdfjs-dist", version: metadata.version, licenseFiles: Object.values(licenses), assets: inventory, totalBytes: inventory.reduce((sum, item) => sum + item.bytes, 0) }, null, 2) + "\n");
